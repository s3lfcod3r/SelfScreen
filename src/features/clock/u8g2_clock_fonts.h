// Extracted verbatim from the U8g2 project's csrc/u8g2_fonts.c
// (github.com/olikraus/u8g2, BSD-2-Clause). Each array keeps its
// U8G2_FONT_SECTION(name) attribute so it lands in FLASH (irom on
// ESP8266, drom on ESP32), read via pgm_read_byte by Arduino_GFX's
// U8g2 font renderer - never in RAM like the old Adafruit GFXfonts.
//
// Two ordered font families back the per-element size sliders in the web UI:
//
//   CLK_NUM_FONTS[]  logisoso "_tn" number fonts (digits + ':' + '-'), used for
//                    the big time. Ordered small -> large: 16, 22, 32, 42, 50,
//                    62, 78 px. Index = ClockFaceSettings::timeSize.
//   CLK_PROP_FONTS[] Helvetica Bold "_tr" proportional fonts (ASCII letters),
//                    used for weekday, date and the AM/PM marker. Ordered
//                    small -> large: helvB 08, 10, 12, 14, 18, 24. Index =
//                    ClockFaceSettings::weekdaySize / dateSize.
//
// The counts and default indices live in config.h (CLK_NUM_FONT_COUNT /
// CLK_PROP_FONT_COUNT / DEFAULT_CLK_*SIZE) so the web UI slider ranges and the
// settings clamps stay in sync with the arrays below (static_assert guards it).
#pragma once
#include <Arduino.h>  // pgm_read_byte / PROGMEM
#include "config.h"

// When Arduino_GFX is built without <U8g2lib.h> on the include path (we
// enable its U8g2 renderer via -D U8G2_FONT_SUPPORT instead, to avoid
// dragging in the library's ~6 MB of bundled CJK fonts), the
// U8G2_FONT_SECTION macro is not provided - define it here. On ESP8266
// this MUST map to PROGMEM so the array is placed in flash (.irom);
// a plain const would land in DRAM. On ESP32 const data is already
// flash-backed, so an empty attribute is correct.
#ifndef U8G2_FONT_SECTION
  #if defined(ESP8266)
    #define U8G2_FONT_SECTION(name) PROGMEM
  #else
    #define U8G2_FONT_SECTION(name)
  #endif
#endif

